// Generates src/content/ui/icons.ts from lucide (one icon set, 16px, stroke 1.5).
// Run: node scripts/gen-icons.mjs
import { writeFileSync } from 'node:fs';

const NAMES = {
  settings: 'settings', close: 'x', copy: 'copy', fill: 'pen-line', undo: 'undo-2', file: 'file-text',
  video: 'circle-play', search: 'search', link: 'arrow-up-left', check: 'check', scan: 'scan-search',
  download: 'download', book: 'book-open', pick: 'mouse-pointer-click', trash: 'trash', eye: 'eye',
  alert: 'triangle-exclamation-point', refresh: 'rotate-ccw', plus: 'list-plus', notebook: 'notebook-pen',
  camera: 'camera', review: 'clipboard-check', save: 'clock', history: 'clock',
  sliders: 'settings-2', back: 'arrow-right', window: 'app-window', pause: 'pause', chevron: 'chevron-down',
  key: 'key-round', external: 'external-link', stop: 'square', board: 'layout-dashboard', chat: 'message-circle',
  send: 'arrow-up', answers: 'list-checks', scan: 'scan-search',
};

const attrs = (o) => Object.entries(o).map(([k, v]) => `${k}="${v}"`).join(' ');
const out = [];
for (const [key, name] of Object.entries(NAMES)) {
  const { default: nodes } = await import(`../node_modules/lucide/dist/esm/icons/${name}.mjs`);
  const inner = nodes.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join('');
  out.push(`  ${key}: '${inner}',`);
}
writeFileSync(
  'src/content/ui/icons.ts',
  `// Generated by scripts/gen-icons.mjs from lucide (ISC license). Do not edit by hand.
const PATHS = {
${out.join('\n')}
} as const;

export type IconName = keyof typeof PATHS;

/** A lucide line icon, 16px, stroke 1.5, colored by the text around it. */
export function icon(name: IconName, size = 16): SVGSVGElement {
  const tpl = document.createElement('template');
  tpl.innerHTML = \`<svg xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${PATHS[name]}</svg>\`;
  return tpl.content.firstElementChild as SVGSVGElement;
}
`,
);
console.log(`wrote ${Object.keys(NAMES).length} icons`);
